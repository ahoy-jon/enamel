import pg from "pg";
import { writeFile } from "node:fs/promises";

if (!process.env.DATABASE_URL) {
  throw new Error("DATABASE_URL is required to dump the database schema");
}

const cue = (value) => JSON.stringify(value);
const cueList = (values, indent) =>
  `[${[...values].sort().map((value) => `\n${indent}${cue(value)},`).join("")}\n${indent.slice(0, -1)}]`;

const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL });
try {
  const [columns, enums, constraints] = await Promise.all([
    pool.query("SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = 'public' ORDER BY table_name, column_name"),
    pool.query("SELECT t.typname AS type_name, e.enumlabel AS enum_value FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid JOIN pg_namespace n ON n.oid = t.typnamespace WHERE n.nspname = 'public' ORDER BY t.typname, e.enumlabel"),
    pool.query("SELECT c.relname AS table_name, pg_get_constraintdef(k.oid) AS definition FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' ORDER BY c.relname, pg_get_constraintdef(k.oid)"),
  ]);

  const tables = new Map();
  const enumValues = new Map();
  for (const { table_name, column_name } of columns.rows) (tables.get(table_name) ?? tables.set(table_name, []).get(table_name)).push(column_name);
  for (const { type_name, enum_value } of enums.rows) (enumValues.get(type_name) ?? enumValues.set(type_name, []).get(type_name)).push(enum_value);

  const output = `// Code generated by tools/dump-database-schema.mjs; DO NOT EDIT.
// Regenerate with: DATABASE_URL=... npm run schema:database
package subscription

// State observed from PostgreSQL's catalog; no application source is consulted.
databaseSchema: {
	tables: {${[...tables].sort(([a], [b]) => a.localeCompare(b)).map(([table, tableColumns]) => `
		${table}: { columns: ${cueList(tableColumns, "\t\t\t")} }`).join("")}
	}
	enums: {${[...enumValues].sort(([a], [b]) => a.localeCompare(b)).map(([name, values]) => `
		${name}: { values: ${cueList(values, "\t\t\t")} }`).join("")}
	}
	constraints: ${cueList(constraints.rows.map(({ definition }) => definition), "\t\t")}
}
`;
  await writeFile(new URL("../enamel/database-schema.gen.cue", import.meta.url), output);
} finally {
  await pool.end();
}
