import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("..", import.meta.url);
const read = (path) => readFile(new URL(path, root), "utf8");
const cue = (value) => JSON.stringify(value);

const cueList = (values, indent) =>
  `[${[...values].sort().map((value) => `\n${indent}${cue(value)},`).join("")}\n${indent.slice(0, -1)}]`;

const main = async () => {
  const [contract, domain] = await Promise.all([
    read("src/enamel/database-contract.ts"),
    read("src/domain/subscription.ts"),
  ]);
  const tables = [...contract.matchAll(/\s+(\w+): \[([^\]]+)]/g)].map((match) => ({
    name: match[1],
    columns: [...match[2].matchAll(/"([^"]+)"/g)].map((column) => column[1]),
  }));
  const constraints = [...(contract.match(/const requiredConstraints = \[([\s\S]*?)]/)?.[1].matchAll(/"([^"]+)"/g) ?? [])].map((match) => match[1]);
  const statuses = [...(domain.match(/subscriptionStatuses\s*=\s*\[([^\]]+)]/)?.[1].matchAll(/"([^"]+)"/g) ?? [])].map((match) => match[1]);

  if (!tables.length || !constraints.length || !statuses.length) {
    throw new Error("Could not extract the program's database contract");
  }

  const output = `// Code generated by tools/extract-program-schema.mjs; DO NOT EDIT.
// Regenerate with: npm run schema:program
package subscription

// The database shape the running program currently relies on.
programSchema: {
	tables: {${tables.sort((a, b) => a.name.localeCompare(b.name)).map((table) => `
		${table.name}: { columns: ${cueList(table.columns, "\t\t\t")} }`).join("")}
	}
	enums: {
		subscription_status: {
			// Statuses are exact: an unrecognised persisted state is unsafe.
			values: ${cueList(statuses, "\t\t\t\t")}
		}
	}
	constraints: ${cueList(constraints, "\t\t")}
}
`;
  await writeFile(new URL("enamel/program-schema.gen.cue", root), output);
};

await main();
